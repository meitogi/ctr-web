"""The NTSC-U → PAL maps of the platform's "US view" of a PAL disc, as a C header.

	python3 -I tools/extract/view_maps.py <us_out> <pal_out> <pal-diff.json> platform/web_disc_view_maps.h

Reads what extract.py and diff.py wrote and emits index tables only (numbers, no disc data) :
the BIGFILE entry per language, the LNG string ids, the XA song ids, the KART.HWL OtherFX and
banks. `platform/web_disc_view.c` applies them when a PAL disc is read.
"""

import json
import os
import sys

LANGUAGES = ["en", "fr", "de", "it", "es", "nl"]
BIGFILE_LANGUAGE = {"en": (None, "ENG"), "fr": ("FRN",), "de": ("GRM",), "it": ("ITL",), "es": ("SPN",), "nl": ("DCH",)}
VOICE_SETS_PAL_FALLS_BACK = 8  # US voice sets 8-10 (types 21-23) : PAL plays set 0 (PAL-DIFF.md §4)


def read_json(path):
	with open(path, encoding="utf-8") as f:
		return json.load(f)


def bigfile_maps(pal_index, us_count):
	"""Per language : US BIGFILE index -> PAL index (the language's copy where PAL has one)."""
	out = {}
	for code in LANGUAGES:
		m = [None] * us_count
		for e in pal_index["entries"]:
			u = e["us_index"]
			if u is None or u >= us_count:
				continue
			if e["language"] in BIGFILE_LANGUAGE[code] or (m[u] is None and e["language"] in (None, "ENG")):
				m[u] = e["index"]
		if None in m:
			raise ValueError(f"{code}: US BIGFILE entries without a PAL entry: {[i for i, p in enumerate(m) if p is None]}")
		out[code] = m
	return out


def game_song_map(diff, us_voice):
	"""US GAME song id -> PAL id : the voiceData map, voice sets PAL does not have fall back to
	the character's set 0 as PAL plays them, the songs past voiceData by length, else silent."""
	voice = {int(k): v for k, v in diff["voice_map_us_to_pal"]["map"].items()}
	by_length = diff["xa_map_us_to_pal"]["GAME"]["map"]
	out = []
	for i, j in enumerate(by_length):
		out.append(voice[i] if i in voice else j)
	for c in us_voice["characters"]:
		sets, index = c["sets"], c["index"]
		first0, n0 = sets[0]
		for s in range(VOICE_SETS_PAL_FALLS_BACK, len(sets)):
			first, num = sets[s]
			for n in range(num):
				us_id = index[first + n]
				if out[us_id] is None:
					out[us_id] = voice[index[first0 + n % n0]]
	return out


def c_array(ctype, name, values, per_line=24):
	rows = [", ".join(str(-1 if v is None else v) for v in values[i:i + per_line]) for i in range(0, len(values), per_line)]
	return f"static const {ctype} {name}[{len(values)}] = {{\n\t" + ",\n\t".join(rows) + "\n};\n"


def generate(us_out, pal_out, diff_path):
	diff = read_json(diff_path)
	pal_index = read_json(os.path.join(pal_out, "bigfile", "index.json"))
	us_voice = read_json(os.path.join(us_out, "exe", "tables.json"))["voiceData"][0]
	hwl = diff["hwl_view"]
	if hwl["sample_conflicts"] or hwl["us_samples_unmatched"] or any(r["fx_sample_mismatch"] or r["fx_field_mismatch"] for r in hwl["languages"].values()):
		raise ValueError("the KART.HWL map is not proven (see diff.py's KART.HWL section)")
	us_count = diff["bigfile"]["us_count"]
	big = bigfile_maps(pal_index, us_count)
	xa = diff["xa_map_us_to_pal"]
	game = game_song_map(diff, us_voice)

	out = ['// Generated by tools/extract/view_maps.py from the two discs\' extractions : do not edit.',
		'// Index tables only (US id -> PAL id) ; -1 : the PAL disc has no counterpart.',
		'// PAL language index : 0 en, 1 fr, 2 de, 3 it, 4 es, 5 nl (PAL-DIFF, KART.HWL section).',
		'',
		f'#define WEB_DISC_VIEW_LANGUAGES  {len(LANGUAGES)}',
		f'#define WEB_DISC_VIEW_BIG_ENTRIES {us_count}',
		f'#define WEB_DISC_VIEW_LNG_STRINGS {len(diff["lng_id_map_us_to_pal"])}',
		f'#define WEB_DISC_VIEW_OTHERFX   {hwl["us"]["otherfx"]}',
		f'#define WEB_DISC_VIEW_BANKS     {hwl["us"]["banks"]}',
		'']
	out.append(c_array("u16", f"s_webViewBigfile[WEB_DISC_VIEW_LANGUAGES * WEB_DISC_VIEW_BIG_ENTRIES]", sum((big[c] for c in LANGUAGES), [])).replace(f"[{6 * us_count}]", ""))
	out.append(c_array("u16", "s_webViewLng", diff["lng_id_map_us_to_pal"]))
	out.append(c_array("s16", "s_webViewXaMusic", xa["MUSIC"]["map"]))
	out.append(c_array("s16", "s_webViewXaExtra", xa["EXTRA"]["map"]))
	out.append(c_array("s16", "s_webViewXaGame", game))
	fx, banks, assembled, starts = [], [], [], []
	for code in LANGUAGES:
		r = hwl["languages"][code]
		fx += r["otherfx"]
		for b in r["banks"]:
			if "pal" in b:
				banks.append(b["pal"])
			else:
				banks.append(-2 - len(starts))  # -2 - k : assembled bank k
				starts.append(len(assembled))
				assembled += [len(b["samples"])] + [x for pair in zip(b["samples"], b["from"]) for x in pair]
	out.append(c_array("u16", "s_webViewOtherFX[WEB_DISC_VIEW_LANGUAGES * WEB_DISC_VIEW_OTHERFX]", fx).replace(f"[{len(fx)}]", ""))
	out.append("// PAL bank id, or -2 - k for the k-th assembled bank (s_webViewAssembledAt[k] : its count, then per sample its PAL spu index and the PAL bank holding it)")
	out.append(c_array("s16", "s_webViewBanks[WEB_DISC_VIEW_LANGUAGES * WEB_DISC_VIEW_BANKS]", banks).replace(f"[{len(banks)}]", ""))
	out.append(c_array("u16", "s_webViewAssembledAt", starts))
	out.append(c_array("u16", "s_webViewAssembled", assembled))
	return "\n".join(out)


def main(argv):
	if len(argv) != 5:
		print(__doc__.strip(), file=sys.stderr)
		return 2
	text = generate(argv[1], argv[2], argv[3])
	with open(argv[4], "w", encoding="utf-8") as f:
		f.write(text)
	return 0


if __name__ == "__main__":
	sys.exit(main(sys.argv))
